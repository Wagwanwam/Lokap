fun buildPolygonPath(
    points: FloatArray,
    mapWidth: Float,
    mapHeight: Float,
    offsetX: Float,
    offsetY: Float
): Path {
    val path = Path()
    if (points.size < 2) return path

    val startX = offsetX + points[0] * mapWidth
    val startY = offsetY + points[1] * mapHeight
    path.moveTo(startX, startY)

    var i = 2
    while (i < points.size) {
        val px = offsetX + points[i] * mapWidth
        val py = offsetY + points[i + 1] * mapHeight
        path.lineTo(px, py)
        i += 2
    }
    path.close()
    return path
}
